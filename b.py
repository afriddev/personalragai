from pyvis.network import Network
import networkx as nx
import uuid
import random
from community import community_louvain  # pip install python-louvain

def build_relation_map(sub_arrays):
    rel_map = {}
    for i, sub in enumerate(sub_arrays):
        for rel in sub:
            rel_map.setdefault(str(rel), []).append(i)
    return rel_map

def create_interactive_graph(sub_arrays, output="graph.html"):
    # create network (interactive)
    net = Network(height="800px", width="100%", notebook=False, directed=False)
    net.barnes_hut()  # reasonable default physics; user can tweak in UI

    # create a networkx graph to detect communities
    G = nx.Graph()
    n = len(sub_arrays)
    for i, sub in enumerate(sub_arrays):
        G.add_node(i, full_rels=[str(x) for x in sub])

    # add edges (shared relations), add title to edges for hover
    rel_map = build_relation_map(sub_arrays)
    for rel, nodes in rel_map.items():
        for a in range(len(nodes)):
            for b in range(a + 1, len(nodes)):
                if G.has_edge(nodes[a], nodes[b]):
                    # don't add duplicate edges in networkx; but add rel to edge data
                    G[nodes[a]][nodes[b]]['rels'].append(rel)
                else:
                    G.add_edge(nodes[a], nodes[b], rels=[rel])

    # community detection to color nodes
    if G.number_of_nodes() > 0 and G.number_of_edges() > 0:
        partition = community_louvain.best_partition(G)
    else:
        partition = {i: 0 for i in G.nodes()}

    # map partition -> color (simple palette)
    palette = [
        "#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd",
        "#8c564b", "#e377c2", "#7f7f7f", "#bcbd22", "#17becf"
    ]

    # Add nodes to pyvis with short label and full info in tooltip
    for node, data in G.nodes(data=True):
        cluster = partition.get(node, 0)
        color = palette[cluster % len(palette)]
        short_label = f"Node {node}"
        title = "<b>Node {}</b><br>Relations:<br>{}".format(
            node,
            "<br>".join(data.get("full_rels", [])) or "None"
        )
        net.add_node(node, label=short_label, title=title, color=color, size=20)

    # Add edges to pyvis with title listing shared relations (shown on hover)
    for u, v, data in G.edges(data=True):
        rels = data.get("rels", [])
        # limit shown relations to avoid massive tooltips
        title = "Shared relations: " + ", ".join(r[:8] for r in rels[:10])
        if len(rels) > 10:
            title += f" (+{len(rels)-10} more)"
        net.add_edge(u, v, title=title, smooth={"type": "dynamic"})

    # Add physics configuration panel to tweak in browser
    net.show_buttons(filter_=['physics'])
    net.set_options("""
    var options = {
      "physics": {
        "barnesHut": {"gravitationalConstant": -8000, "springLength": 200},
        "minVelocity": 0.75
      },
      "nodes": {
        "font": {"size": 14, "strokeWidth": 2}
      }
    }
    """)
    # Write HTML and print path
    net.show(output)
    print("Wrote", output)

